"""Run agents over the dataset and render the metrics table / markdown report."""
from .agents import CarefulAgent, SloppyAgent
from .dataset import load_dataset
from .judge import aggregate, evaluate_agent

HEADLINE = (
    ("Extraction acc %", "extraction_accuracy"),
    ("Hallucination %", "hallucination_rate"),
    ("Recon error %", "reconciliation_error_rate"),
    ("Traceability %", "traceability"),
)
LAYER_B = (
    ("Restatement flagged %", "restatement_flag_rate"),
    ("Distribution reconciled %", "distribution_reconciled_rate"),
)


def build_results(dataset=None, agents=None):
    dataset = dataset or load_dataset()
    agents = agents or [CarefulAgent(), SloppyAgent()]
    results = {}
    for agent in agents:
        scores = evaluate_agent(agent, dataset)
        results[agent.name] = {
            "overall": aggregate(scores),
            "institutions": {inst: aggregate([s for s in scores if s.institution == inst])
                             for inst in dataset.institutions},
            "docs": scores,
        }
    return results


def _fmt(v):
    return "n/a" if v is None else "%.1f" % v


def render_table(results, columns=HEADLINE):
    agents = list(results)
    scopes = [("OVERALL", lambda a: results[a]["overall"])]
    for inst in results[agents[0]]["institutions"]:
        scopes.append((inst, (lambda i: lambda a: results[a]["institutions"][i])(inst)))
    width = max(len(s[0]) for s in scopes)
    header = "%-*s  %-8s" % (width, "Scope", "Agent") + "".join("  %-*s" % (len(c[0]), c[0]) for c in columns)
    lines = [header, "-" * len(header)]
    for label, getter in scopes:
        for a in agents:
            m = getter(a)
            row = "%-*s  %-8s" % (width, label, a)
            row += "".join("  %-*s" % (len(c[0]), _fmt(m[c[1]])) for c in columns)
            lines.append(row)
    return "\n".join(lines)


def render_markdown(results, dataset):
    agents = list(results)
    out = []
    out.append("# Finpilot agent reliability eval - sample report")
    out.append("")
    out.append("> **SYNTHETIC DATA.** Fictional institutions, funds and figures. This measures the eval "
               "method on two rule-based reference agents, not production accuracy.")
    out.append("> Generated by `demo.py` (actually executed; deterministic, no randomness).")
    out.append("")
    out.append("## Headline metrics (Layer A + traceability/reconciliation)")
    out.append("")
    out.append("```")
    out.append(render_table(results))
    out.append("```")
    out.append("")
    out.append("## Layer B: reconciliation quality (trap documents only)")
    out.append("")
    out.append("```")
    out.append(render_table(results, LAYER_B))
    out.append("```")
    out.append("")
    out.append("## Per-document fields correct (of 7)")
    out.append("")
    out.append("| Document | Institution | Traps | " + " | ".join(agents) + " |")
    out.append("|---|---|---|" + "---|" * len(agents))
    for i, (doc_id, t) in enumerate(dataset.truth.items()):
        cells = ["%d/%d" % (results[a]["docs"][i].fields_correct, results[a]["docs"][i].fields_total)
                 for a in agents]
        out.append("| %s | %s | %s | %s |" % (doc_id, t["institution"], ", ".join(t["traps"]) or "-",
                                              " | ".join(cells)))
    out.append("")
    out.append("## Metric definitions")
    out.append("")
    out.append("- **Extraction accuracy**: correct fields / total fields (7 per doc). Identifiers exact; "
               "currency within $1; percent within 0.05 pt; a truly-absent field is correct only if reported missing.")
    out.append("- **Hallucination rate**: reported non-zero numbers appearing in no source document / reported numbers.")
    out.append("- **Reconciliation error rate**: documents whose reported contributions/distributions disagree "
               "with the ledger / documents checked.")
    out.append("- **Traceability**: reported numbers whose cited source exists and contains the value / reported numbers.")
    return "\n".join(out) + "\n"


def write_report(path, results=None, dataset=None):
    dataset = dataset or load_dataset()
    results = results or build_results(dataset)
    text = render_markdown(results, dataset)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(text)
    return text
